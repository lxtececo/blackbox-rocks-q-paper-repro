def analyse_circuit(task) -> list:
    """One instance: the counts of its seven bindings -> one row per binding."""
    import core.optimizers.quantum.ibm.qaoa_circuit as qaoa
    from core.portfolio_referee import referee
    from qiskit.transpiler import generate_preset_pass_manager
    from qiskit_aer import AerSimulator

    n, instance, bindings, counts = task
    logging.disable(logging.CRITICAL)
    _, linear, quadratic, ansatz, cost = problem(n, instance)
    product_cost = qaoa._qubo_cost_of_key(linear, quadratic, n)
    if max(abs(product_cost(key) - cost[key]) for key in range(len(cost))) > 1e-9:
        raise RuntimeError("the product's cost of an outcome differs from the enumeration")

    def cost_of(key: int) -> float:
        return float(cost[key])

    lo, mean = float(cost.min()), float(cost.mean())
    optimal_keys = np.flatnonzero(cost <= lo + 1e-9 * max(1.0, abs(lo)))
    share = len(optimal_keys) / len(cost)

    def p_contains_optimum(samples: int) -> float:
        return -math.expm1(samples * math.log1p(-share))

    logical = generate_preset_pass_manager(backend=AerSimulator(), optimization_level=1).run(ansatz)
    rows = []
    for index, (binding, count) in enumerate(zip(bindings, counts)):
        count = {int(k): int(v) for k, v in count.items()}
        shots = sum(count.values())
        ideal = e19.state_metrics(e19.exact_probabilities(
            logical.assign_parameters({p: binding["values"][p.name] for p in logical.parameters})), cost)
        if binding["arm"] != "qaoa" and abs(ideal["p_optimum_over_uniform"] - 1.0) > 1e-9:
            raise RuntimeError(f"{binding['arm']} is not uniform in the exact state")

        key, _ = qaoa._select_sample(count, cost_of)
        full = e19.score(cost, key)
        reference = referee(linear, quadratic, [(key >> i) & 1 for i in range(n)], sampled_shots=shots)

        keys = np.array(sorted(count))
        order = np.repeat(keys, [count[int(k)] for k in keys])
        np.random.default_rng(point_seed(22, 0, n, instance, index)).shuffle(order)
        batch_scores = []
        for b in range(shots // BATCH):
            batch_key, _ = qaoa._select_sample(Counter(order[b * BATCH:(b + 1) * BATCH].tolist()), cost_of)
            batch_scores.append(e19.score(cost, batch_key))

        sampled_mean = sum(cost[k] * c for k, c in count.items()) / shots
        rows.append({
            "n": n, "instance": instance, "arm": binding["arm"], "rep": binding["rep"], "binding": index, "shots": shots,
            "full_gap": full["gap"], "full_optimal": full["optimal"], "full_rank_pct": full["rank_pct"],
            "referee_agrees": e20.referee_agrees(reference, full),
            "full_uniform_p_optimum": p_contains_optimum(shots),
            "full_uniform_p_optimum_product": reference["uniform_null"]["p_returns_an_optimum"],
            "batches": len(batch_scores),
            "batch_gap": float(np.mean([s["gap"] for s in batch_scores])),
            "batch_optimal": float(np.mean([s["optimal"] for s in batch_scores])),
            "batch_rank_pct": float(np.mean([s["rank_pct"] for s in batch_scores])),
            "batch_uniform_p_optimum": p_contains_optimum(BATCH),
            "optimum_shots": int(sum(count.get(int(k), 0) for k in optimal_keys)),
            "p_optimum": float(sum(count.get(int(k), 0) for k in optimal_keys)) / shots,
            "p_optimum_uniform": share,
            "ratio": float((mean - sampled_mean) / (mean - lo)),
            "ideal_p_optimum": ideal["p_optimum"], "ideal_ratio": ideal["approx_ratio"],
        })
    return rows


def by_instance(rows, field) -> dict:
    return e19.per_instance(rows, field)


def paired(a: dict, b: dict) -> dict:
    diff = [a[i] - b[i] for i in sorted(set(a) & set(b))]
    return {"difference": mean_ci(diff),
            "wilcoxon_p": float(wilcoxon(diff).pvalue) if any(abs(d) > 1e-12 for d in diff) else None}


def summarise(rows) -> dict:
    stored = json.loads((RESULTS / "e21_qaoa_fresh.json").read_text())["rows"] if not QUICK else []
    out = {}
    for n in sorted({r["n"] for r in rows}):
        sel = [r for r in rows if r["n"] == n]
        q = [r for r in sel if r["arm"] == "qaoa"]
        u = [r for r in sel if r["arm"] != "qaoa"]
        cell = {"bindings": {"qaoa": len(q), "null": len(u)}, "shots": {"qaoa": sum(r["shots"] for r in q),
                                                                           "null": sum(r["shots"] for r in u)},
                "referee_disagreements": int(sum(not r["referee_agrees"] for r in sel)),
                "uniform_null_differs_from_product": float(max(
                    abs(r["full_uniform_p_optimum"] - r["full_uniform_p_optimum_product"]) for r in sel))}
        for rule in ("batch", "full"):
            mg, ug = by_instance(q, f"{rule}_gap"), by_instance(u, f"{rule}_gap")
            cell[rule] = {
                "qaoa": {"gap": mean_ci(list(mg.values())), "gap_by_instance": mg,
                         "rank_pct": mean_ci(list(by_instance(q, f"{rule}_rank_pct").values())),
                         "optimal_share": float(np.mean([r[f"{rule}_optimal"] for r in q]))},
                "null": {"gap": mean_ci(list(ug.values())), "gap_by_instance": ug,
                         "rank_pct": mean_ci(list(by_instance(u, f"{rule}_rank_pct").values())),
                         "optimal_share": float(np.mean([r[f"{rule}_optimal"] for r in u]))},
                "uniform_exact_optimal_share": float(np.mean([r[f"{rule}_uniform_p_optimum"] for r in sel])),
                "qaoa_vs_null": e20.paired_test(mg, ug),
            }
        cell["full"]["qaoa"]["optimal_runs"] = int(sum(r["full_optimal"] for r in q))
        cell["full"]["null"]["optimal_runs"] = int(sum(r["full_optimal"] for r in u))

        pq, pu = by_instance(q, "p_optimum"), by_instance(u, "p_optimum")
        pi, p0 = by_instance(q, "ideal_p_optimum"), by_instance(sel, "p_optimum_uniform")
        ids = sorted(pq)
        rng = np.random.default_rng(point_seed(22, 3, n))
        boot = []
        for _ in range(BOOT):
            draw = rng.choice(ids, len(ids))
            boot.append((np.mean([pq[i] for i in draw]) - np.mean([pu[i] for i in draw]))
                        / (np.mean([pi[i] for i in draw]) - np.mean([p0[i] for i in draw])))
        cell["p_optimum"] = {
            "qaoa": mean_ci(list(pq.values())), "null": mean_ci(list(pu.values())),
            "uniform": float(np.mean(list(p0.values()))), "ideal": mean_ci(list(pi.values())),
            "qaoa_optimum_shots": int(sum(r["optimum_shots"] for r in q)),
            "null_optimum_shots": int(sum(r["optimum_shots"] for r in u)),
            "null_optimum_shots_expected_if_uniform": float(sum(r["shots"] * r["p_optimum_uniform"] for r in u)),
            "retained_fraction": {"estimate": float((np.mean(list(pq.values())) - np.mean(list(pu.values())))
                                                    / (np.mean(list(pi.values())) - np.mean(list(p0.values())))),
                                  "ci95": [float(x) for x in np.percentile(boot, [2.5, 97.5])]},
        }
        rq, ru = by_instance(q, "ratio"), by_instance(u, "ratio")
        rg = by_instance([r for r in u if r["arm"] == "null_gamma"], "ratio")
        rb = by_instance([r for r in u if r["arm"] == "null_beta"], "ratio")
        cell["approx_ratio"] = {
            "qaoa": mean_ci(list(rq.values())), "null": mean_ci(list(ru.values())),
            "ideal": mean_ci(list(by_instance(q, "ideal_ratio").values())),
            "null_against_zero_wilcoxon_p": float(wilcoxon(list(ru.values())).pvalue),
            "null_gamma_minus_null_beta": paired(rg, rb),
        }
        if stored:
            old = {(r["instance"], r["rep"]): r["state"]["p_optimum"] for r in stored if r["n"] == n and not r["null"]}
            cell["exact_state_differs_from_e21"] = float(max(
                abs(r["ideal_p_optimum"] - old[(r["instance"], r["rep"])]) for r in q))
            cell["simulator_e21"] = {
                "qaoa_optimal_runs": int(sum(r["optimal"] for r in stored if r["n"] == n and not r["null"])),
                "null_optimal_runs": int(sum(r["optimal"] for r in stored if r["n"] == n and r["null"])),
                "runs": int(sum(1 for r in stored if r["n"] == n and not r["null"]))}
        out[str(n)] = cell
    return out


def report(summary: dict) -> None:
    for n, cell in summary.items():
        for rule, label in (("batch", f"{BATCH} shots"), ("full", "all shots")):
            c, t = cell[rule], cell[rule]["qaoa_vs_null"]
            print(f"{n:>2} assets, {label:>9}: gap {c['qaoa']['gap']['mean']:.4f}±{c['qaoa']['gap']['ci95']:.4f} vs null "
                  f"{c['null']['gap']['mean']:.4f}±{c['null']['gap']['ci95']:.4f} better/worse/tied "
                  f"{t['method_better']}/{t['null_better']}/{t['ties']} p={t['wilcoxon_p']} | optimal share "
                  f"{c['qaoa']['optimal_share']:.3f} vs {c['null']['optimal_share']:.3f} (uniform exact "
                  f"{c['uniform_exact_optimal_share']:.3f})", flush=True)
        p, r = cell["p_optimum"], cell["approx_ratio"]
        print(f"   P(optimum) {p['qaoa']['mean']:.5f} vs null {p['null']['mean']:.5f} (uniform {p['uniform']:.5f}, ideal "
              f"{p['ideal']['mean']:.5f}); retained {p['retained_fraction']['estimate']:.3f} "
              f"[{p['retained_fraction']['ci95'][0]:.3f}, {p['retained_fraction']['ci95'][1]:.3f}] | ratio "
              f"{r['qaoa']['mean']:.3f} vs null {r['null']['mean']:+.4f} (ideal {r['ideal']['mean']:.3f}) | referee "
              f"disagreements {cell['referee_disagreements']}", flush=True)


def analyse(entries: list) -> list:
    """entries: dicts with n, instance, bindings, counts."""
    tasks = [(e["n"], e["instance"], e["bindings"], e["counts"]) for e in entries]
    with ProcessPoolExecutor(max_workers=pool_workers()) as pool:
        return [row for rows in pool.map(analyse_circuit, tasks) for row in rows]


# --------------------------------------------------------------------------- Aer (validates the analysis)


def simulate_circuit(task) -> list:
    from qiskit import transpile
    from qiskit_aer import AerSimulator
    from qiskit_aer.noise import NoiseModel, depolarizing_error

    n, instance, bindings, noise = task
    logging.disable(logging.CRITICAL)
    ansatz = problem(n, instance)[3]
    logical = transpile(ansatz, basis_gates=["cx", "rz", "sx", "x"], optimization_level=1, seed_transpiler=0)
    model = None
    if noise:
        model = NoiseModel()
        model.add_all_qubit_quantum_error(depolarizing_error(noise, 2), ["cx"])
    counts = []
    for index, binding in enumerate(bindings):
        bound = logical.assign_parameters({p: binding["values"][p.name] for p in logical.parameters})
        sim = AerSimulator(noise_model=model, seed_simulator=int(point_seed(22, 2, n, instance, index) % (2 ** 31 - 1)))
        counts.append({str(int(k, 2)): int(v) for k, v in sim.run(bound, shots=SHOTS[n]).result().get_counts().items()})
    return counts


def dry_run() -> None:
    e20.check_defaults()
    started = time.time()
    cells = [(n, i) for n in SIZES for i in range(FIRST_INSTANCE, FIRST_INSTANCE + INSTANCES)]
    runs = trained_runs(cells)
    check = None if QUICK else check_against_e21(runs)
    entries = [{"n": n, "instance": i, "bindings": bindings_for(problem(n, i)[3], runs, n, i)} for n, i in cells]
    with ProcessPoolExecutor(max_workers=pool_workers()) as pool:
        for entry, counts in zip(entries, pool.map(simulate_circuit, [(e["n"], e["instance"], e["bindings"], NOISE)
                                                                       for e in entries])):
            entry["counts"] = counts
    rows = analyse(entries)
    summary = summarise(rows)
    print(f"Aer, two-qubit depolarising error {NOISE or 0}: {len(rows)} bindings, {time.time() - started:.0f} s", flush=True)
    report(summary)
    name = ("e22_dry_run" + (f"_noise_{NOISE}" if NOISE else "") + ("_quick" if QUICK else "")
            + ("" if SIZES == [8, 12, 16] else "_n" + "_".join(str(n) for n in SIZES)))
    save(name, {"design": __doc__.split("Usage")[0].strip(), "execution": f"Aer, two-qubit depolarising error {NOISE or 0}",
                "defaults": D, "shots": SHOTS, "batch": BATCH, "bonferroni_threshold": BONFERRONI,
                "h2_sizes": H2_SIZES, "h2_threshold": H2_THRESHOLD,
                "regenerated_runs": check, "summary": summary, "rows": rows, "wall_s": round(time.time() - started, 1)})


