# --------------------------------------------------------------------------- the problem and its bindings


def problem(n: int, instance: int):
    """The product's QUBO, cost of every selection, and the circuit the product samples."""
    import core.optimizers.quantum.ibm.qaoa_circuit as qaoa
    from qiskit.circuit.library import QAOAAnsatz

    prices = e19.make_prices(n, INSTANCE_BASE + 100 * (n // 4) + instance)
    linear, quadratic, _ = qaoa._build_qubo(prices, D["risk_aversion"])
    ansatz = QAOAAnsatz(cost_operator=qaoa._build_hamiltonian(linear, quadratic, n), reps=D["reps"])
    ansatz.measure_all()
    return prices, linear, quadratic, ansatz, e19.pair_costs(linear, quadratic, n)


def train(task) -> dict:
    """The product's simulator path with the E21 seed; returns the trained angles and the E21 score."""
    import core.optimizers.quantum.ibm.qaoa_circuit as qaoa

    n, instance, rep = task
    logging.disable(logging.CRITICAL)
    prices, _, _, _, cost = problem(n, instance)
    seed = int(point_seed(21, 0, n, instance, rep, 0) % (2 ** 31 - 1))
    with e20.quiet():
        result = qaoa.quantum_optimize(prices, risk_aversion=D["risk_aversion"], qc_simulator_mode=True,
                                       estimator_shots=D["estimator_shots"], sampler_shots=D["sampler_shots"],
                                       max_iterations=D["max_iterations"], reps=D["reps"], seed=seed)
    out = e19.score(cost, e19.index_of(result["solution"]))
    out.update(n=n, instance=instance, rep=rep, seed=seed, final_parameters=[float(x) for x in result["final_parameters"]])
    return out


def trained_runs(cells) -> dict:
    tasks = [(n, instance, rep) for n, instance in cells for rep in range(SEEDS)]
    with ProcessPoolExecutor(max_workers=pool_workers()) as pool:
        runs = list(pool.map(train, tasks, chunksize=2))
    return {(r["n"], r["instance"], r["rep"]): r for r in runs}


def check_against_e21(runs: dict) -> dict:
    """Every regenerated run must be its E21 record: same seed, same score."""
    stored = {(r["n"], r["instance"], r["rep"]): r
              for r in json.loads((RESULTS / "e21_qaoa_fresh.json").read_text())["rows"] if not r["null"]}
    same = 0
    for key, run in runs.items():
        old = stored[key]
        same += int(run["seed"] == old["seed"] and run["optimal"] == old["optimal"]
                    and abs(run["gap"] - old["gap"]) <= 1e-12 and abs(run["rank_pct"] - old["rank_pct"]) <= 1e-12)
    if same != len(runs):
        raise SystemExit(f"only {same} of {len(runs)} regenerated runs equal their E21 record; nothing submitted")
    return {"runs": len(runs), "equal_to_e21_record": same}


def bindings_for(ansatz, runs: dict, n: int, instance: int) -> list:
    names = [p.name for p in ansatz.parameters]
    if sorted(names) != sorted([f"β[{k}]" for k in range(D["reps"])] + [f"γ[{k}]" for k in range(D["reps"])]):
        raise SystemExit(f"unexpected ansatz parameters {names}")
    out = [{"arm": "qaoa", "rep": rep, "values": dict(zip(names, runs[(n, instance, rep)]["final_parameters"]))}
           for rep in range(SEEDS)]
    base = out[0]["values"]
    out.append({"arm": "null_gamma", "rep": 0, "values": {k: (0.0 if k.startswith("γ") else v) for k, v in base.items()}})
    out.append({"arm": "null_beta", "rep": 0, "values": {k: (0.0 if k.startswith("β") else v) for k, v in base.items()}})
    return out


