"""E22 - Portfolio QAOA on IBM hardware. Analysis plan fixed before the submission.

Question. E21 showed on the simulator that the product's portfolio QAOA, which
returns the cheapest of its final samples, returns better selections than
uniform sampling under the same rule. Does that survive when the final circuit
is sampled on a device?

What is run
 - Instances and seeds: those of E21 (generator seeds 1000 + 100 (n // 4) + i
   for i = 10..19; 8, 12 and 16 assets; five seeds each). The trained angles
   are regenerated by running the product's simulator path with the E21 seed;
   the script stops unless every regenerated run equals its E21 record.
 - One circuit per instance: the product's ansatz with its measurements
   (QAOAAnsatz of the product's Hamiltonian, depth 2, measure_all), transpiled
   once for the device with free angles and bound seven ways. On the device
   every angle is a virtual Z rotation, so the seven bindings run the same
   physical gate sequence:
     qaoa        the trained angles of seeds 0..4                 (5 bindings)
     null_gamma  every gamma = 0, the betas of seed 0     ideal output uniform
     null_beta   every beta = 0, the gammas of seed 0     ideal output uniform
 - Shots per binding: 10 000 at 16 assets, the size of the final sample on the
   product's hardware path; 4 000 at 8 and 12 assets. Sampler settings of that
   path: optimisation level 3, XY4 dynamical decoupling, gate twirling with
   automatic randomisations.

Differences from the product's hardware path
 - The angles are trained on the simulator and transferred. The product trains
   on the device (12 evaluations of 1 000 shots). On-device training is not
   tested here.
 - The transpiler keeps the best of eight seeds by two-qubit gate count; the
   product makes one unseeded pass.
 - The device is pinned (QFPO_IBM_BACKEND, default ibm_marrakesh, the device
   of the earlier hardware experiments); the product takes the least busy one.

Outcome. The gap g = (c - c_min) / (c_mean - c_min) of the selection that the
product's rule (qaoa_circuit._select_sample: the cheapest sampled selection)
returns, against the exact minimum over all 2^n selections of the product's
QUBO: 0 at the optimum, 1 for the average selection.

 H1 (primary; the simulator path's sample size). The rule applied to batches
    of 200 device shots: the shots of a binding, sorted by outcome, are
    permuted with a fixed seed and cut into disjoint batches of 200 (a
    remainder is left out). Per instance, the mean gap over the batches of the
    five qaoa bindings against the mean over the batches of the two nulls.
    Wilcoxon signed-rank test over the ten instances of a size, two-sided.
    Three comparisons; threshold 0.05 / 3. With ten instances the smallest
    p-value the test can return is 2 / 1024.
 H2 (secondary; the hardware path's sample size; 16 assets only). The rule
    applied to all 10 000 shots of a binding. Per instance, the mean gap of the
    five qaoa bindings against the mean of the two nulls; same test; one
    comparison, threshold 0.05. At 8 and 12 assets 10 000 uniform samples
    contain an optimum with probability 1.00 and 0.91, so the comparison could
    not separate anything there; those sizes run 4 000 shots and their
    all-shots outcome is described only.

Described, not tested
 - the share of batches, and of full samples, that return an optimum: qaoa on
   the device, the nulls on the device, the exact value for uniform sampling,
   and the E21 simulator record of the same runs;
 - the device distribution: the probability of an optimum for qaoa and for the
   nulls against its uniform value and against the exact value for the trained
   state; the retained fraction (p_qaoa - p_null) / (p_ideal - p_uniform) with
   a bootstrap interval over instances; the approximation ratio of the device
   samples, (c_mean - mean sampled cost) / (c_mean - c_min), for qaoa and for
   the nulls against the exact ratio of the trained state;
 - whether the two nulls differ from each other and from uniform sampling
   (approximation ratio of their samples; 0 for uniform bits);
 - per circuit: two-qubit gates, depth, physical qubits, the device's reported
   two-qubit errors and their product over the circuit's gates, the reported
   readout errors, the date of the calibration data; QPU seconds per job;
 - whether the exact reference of the product agrees with the scores computed
   here.

Batches are subsets of one run of a binding, not separate 200-shot jobs: the
comparison assumes that the device's distribution is stable over a job.

No run is excluded. A job that ends in an error is resubmitted once and both
identifiers are reported. Raw counts are archived before any analysis. Job 0
(8 assets, instances 10..14) is submitted first; the others only once its QPU
usage is known and at most MAX_FIRST_JOB_USAGE seconds, read from the job's
metadata without reading its results.

Amendment before any submission. The first version (commit 93e60279) asked for
10 000 shots at every size and tested H2 at every size. The account's
allowance is 10 800 QPU seconds per year, of which 695 were used. Shots at 8
and 12 assets were reduced to 4 000, H2 was restricted to 16 assets, where it
can separate something, and the first-job usage limit was lowered from 400 to
150 seconds. H1 is unchanged. No device data existed when this was changed; a
noiseless dry run of the first version had been looked at.

Usage
  e22_hardware_portfolio_qaoa.py --dry-run [--noise P] [--quick] [--sizes 8,12]
        Aer on the logical circuits; validates the analysis (P: two-qubit
        depolarising error). --quick: two harness instances per size.
        --sizes: dry runs only (a noisy simulation of 16 assets takes about
        two hours per circuit).
  e22_hardware_portfolio_qaoa.py --status          device, usage, job states
  e22_hardware_portfolio_qaoa.py --submit J [J..]  submit jobs J (0..5)
  e22_hardware_portfolio_qaoa.py --resubmit J      once, after an error
  e22_hardware_portfolio_qaoa.py --collect         fetch, archive, analyse
  e22_hardware_portfolio_qaoa.py --analyse         analyse the archived counts
"""

